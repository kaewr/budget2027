-- Run once in Supabase SQL Editor (PostgreSQL 15+), before uploading.
-- Intentionally fails if tables already exist; never drops existing data.
BEGIN;
CREATE TABLE public.node_types (code varchar(32) PRIMARY KEY, label_th varchar(255) NOT NULL);
CREATE TABLE public.plan_types (code varchar(32) PRIMARY KEY, label_th varchar(255) NOT NULL);
CREATE TABLE public.budget_acts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 fiscal_year_be smallint NOT NULL UNIQUE, fiscal_year_ce smallint NOT NULL,
 title varchar(500) NOT NULL, title_en varchar(500),
 period_start date NOT NULL, period_end date NOT NULL, enacted_date date,
 gazette_volume smallint, gazette_issue varchar(32), gazette_date date,
 countersigned_name varchar(255), countersigned_pos varchar(255),
 total_amount bigint NOT NULL CHECK (total_amount >= 0),
 source_file varchar(255), source_pages smallint,
 imported_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.chapters (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 act_id bigint NOT NULL REFERENCES public.budget_acts ON DELETE CASCADE,
 code varchar(16) NOT NULL, chapter_no smallint NOT NULL,
 title varchar(500) NOT NULL, amount bigint, page smallint,
 UNIQUE(act_id,chapter_no), UNIQUE(act_id,code)
);
CREATE TABLE public.sections (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 act_id bigint NOT NULL REFERENCES public.budget_acts ON DELETE CASCADE,
 chapter_id bigint REFERENCES public.chapters ON DELETE CASCADE,
 code varchar(16) NOT NULL, section_no smallint NOT NULL,
 title varchar(500), owner varchar(500), body_text text, amount bigint, page smallint,
 UNIQUE(act_id,section_no), UNIQUE(act_id,code)
);
CREATE TABLE public.entities (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(500) NOT NULL, type varchar(32) NOT NULL REFERENCES public.node_types,
 plan_type varchar(32) REFERENCES public.plan_types, UNIQUE(name,type)
);
CREATE TABLE public.budget_items (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 act_id bigint NOT NULL REFERENCES public.budget_acts ON DELETE CASCADE,
 section_id bigint NOT NULL REFERENCES public.sections ON DELETE CASCADE,
 parent_id bigint REFERENCES public.budget_items ON DELETE CASCADE,
 entity_id bigint NOT NULL REFERENCES public.entities,
 code varchar(64) NOT NULL, level smallint NOT NULL CHECK(level BETWEEN 1 AND 10),
 label varchar(16) NOT NULL, seq_no smallint, sort_order integer NOT NULL,
 name varchar(500) NOT NULL, type varchar(32) NOT NULL REFERENCES public.node_types,
 plan_type varchar(32) REFERENCES public.plan_types,
 amount bigint NOT NULL CHECK(amount >= 0), amount_computed boolean NOT NULL DEFAULT false,
 is_leaf boolean NOT NULL, path_names jsonb NOT NULL, page smallint,
 UNIQUE(act_id,code)
);
CREATE INDEX ix_sections_chapter ON public.sections(chapter_id);
CREATE INDEX ix_entities_type ON public.entities(type);
CREATE INDEX ix_entities_plan ON public.entities(plan_type);
CREATE INDEX ix_items_section ON public.budget_items(section_id,sort_order);
CREATE INDEX ix_items_parent ON public.budget_items(parent_id,sort_order);
CREATE INDEX ix_items_entity ON public.budget_items(entity_id);
CREATE INDEX ix_items_type ON public.budget_items(act_id,type,plan_type);
CREATE INDEX ix_items_node_type ON public.budget_items(type);
CREATE INDEX ix_items_plan_type ON public.budget_items(plan_type);
CREATE INDEX ix_items_code ON public.budget_items(code);
CREATE VIEW public.v_check_parent_sum WITH (security_invoker = true) AS
 SELECT p.id,p.act_id,p.code,p.name,p.amount,SUM(c.amount) AS sum_children
 FROM public.budget_items p JOIN public.budget_items c ON c.parent_id=p.id
 GROUP BY p.id,p.act_id,p.code,p.name,p.amount
 HAVING p.amount <> SUM(c.amount);
-- No public API access until application-specific policies are added.
ALTER TABLE public.node_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.plan_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.budget_acts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chapters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sections ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.entities ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.budget_items ENABLE ROW LEVEL SECURITY;
COMMIT;
